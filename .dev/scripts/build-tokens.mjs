import { writeFile } from "node:fs/promises";
import { FIXED, STRUCTURE, THEME_STRUCTURE } from "@eamonxg/luci-theme-tokens/aurora";
import { block, themeColors } from "@eamonxg/luci-theme-tokens/emit";
import { resolveMode } from "../theme-colors.js";

const light = resolveMode("light");
const dark = resolveMode("dark");
const shadows = {
  "shadow-sm": "var(--app-shadow-sm)",
  "shadow-md": "var(--app-shadow-md)",
  "shadow-lg": "var(--app-shadow-md)",
  "shadow-xl": "var(--app-shadow-lg)",
  "shadow-2xl": "var(--app-shadow-lg)",
};
const css = `/* Generated by scripts/build-tokens.mjs from theme-colors.js. */
${block(":root", light, FIXED.light, STRUCTURE)}}

${block('[data-darkmode="true"]', dark, FIXED.dark)}}

@theme inline {
${themeColors(Object.keys(light))}
${Object.entries({ ...shadows, ...THEME_STRUCTURE }).map(([key, value]) => `  --${key}: ${value};`).join("\n")}
}
`;
await writeFile(new URL("../src/media/_tokens.css", import.meta.url), css);
